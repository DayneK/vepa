#!/usr/bin/env node
// ACO-2 (AC-27): reproducible reconciliation of the historical a3 audit corpus
// against the live law manifests (LAW_INDEXES, LAW_CATEGORIES, solver files).
//
//   node scripts/a3-reconciliation.mjs           # write docs/audit/A3-RECONCILIATION.md
//   node scripts/a3-reconciliation.mjs --check   # fail if the committed report is stale
//
// Lists every a3 claim (progress ledger + stage-1 headers) that disagrees with
// the manifests: retired/renamed laws, index and category mismatches, missing
// solver targets, laws with no a3 coverage, and the corpus-level law count.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';

const { LAW_INDEXES, LAW_COUNT, LAW_TO_CATEGORY, LAW_CATEGORIES } = await import('../src/constants.js');
const ROOT = 'docs/audit/laws/a3';
const OUT = 'docs/audit/A3-RECONCILIATION.md';
const NAME_BY_IDX = Object.fromEntries(Object.entries(LAW_INDEXES).map(([n, i]) => [i, n]));

const ledger = readFileSync(`${ROOT}/audit_progress.md`, 'utf8');
const claims = [];
let cat = null;
for (const line of ledger.split('\n')) {
  const c = line.match(/^## Category: (\w+)/);
  if (c) { cat = c[1].toLowerCase(); continue; }
  const m = line.match(/^\| \*\*#(\d+) ([A-Z0-9_]+)\*\* \|(.*)\|\s*$/);
  if (m) claims.push({ source: 'audit_progress.md', index: +m[1], name: m[2], category: cat, complete: !/\[ \]/.test(m[3]) });
}
const totalClaim = (ledger.match(/\*\*Total Laws\*\*: (\d+)/) || [])[1];

const stage1 = [];
for (const f of readdirSync(`${ROOT}/stage-1`).sort()) {
  const s = readFileSync(`${ROOT}/stage-1/${f}`, 'utf8');
  const head = s.match(/Law #(\d+) — ([A-Z0-9_]+)/);
  const category = (s.match(/\*\*Category\*\*: (\w+)/) || [])[1];
  const target = (s.match(/\*\*Solver Target\*\*: `([^`]+)`/) || [])[1];
  if (head) stage1.push({ source: `stage-1/${f}`, index: +head[1], name: head[2], category: category && category.toLowerCase(), target });
}

const rows = [];
const add = (kind, law, claim, manifest, source) => rows.push({ kind, law, claim, manifest, source });
for (const c of [...claims, ...stage1]) {
  const live = LAW_INDEXES[c.name];
  if (live === undefined) {
    add('retired or renamed', c.name, `#${c.index} ${c.name}${c.complete ? ' (claimed complete)' : ''}`, NAME_BY_IDX[c.index] ? `index ${c.index} is now ${NAME_BY_IDX[c.index]}` : `index ${c.index} unused`, c.source);
    continue;
  }
  if (live !== c.index) add('index mismatch', c.name, `#${c.index}`, `#${live}`, c.source);
  const liveCat = LAW_TO_CATEGORY[live];
  if (c.category && liveCat && c.category !== liveCat) add('category mismatch', c.name, c.category, liveCat, c.source);
  if (c.target && !existsSync(c.target)) add('missing solver target', c.name, c.target, 'file not in tree', c.source);
}
const covered = new Set([...claims, ...stage1].map((c) => c.name));
for (const [name, idx] of Object.entries(LAW_INDEXES).sort((a, b) => a[1] - b[1])) {
  if (!covered.has(name)) add('no a3 coverage', name, '—', `#${idx} ${LAW_TO_CATEGORY[idx] || '?'}`, 'manifest');
}
if (totalClaim && +totalClaim !== LAW_COUNT) add('law count', '(corpus)', `${totalClaim} laws, ${claims.length ? new Set(claims.map((c) => c.category)).size : '?'} categories`, `${LAW_COUNT} laws, ${Object.keys(LAW_CATEGORIES).length} categories`, 'audit_progress.md');

const kinds = [...new Set(rows.map((r) => r.kind))];
let md = `# a3 audit corpus reconciliation (ACO-2)\n\nGenerated by \`node scripts/a3-reconciliation.mjs\` from \`${ROOT}\` (historical, D-009) and the live manifests\n(\`src/constants.js\`: LAW_INDEXES, LAW_CATEGORIES). Do not edit by hand; \`--check\` fails when stale.\n\n`;
md += `Ledger rows: ${claims.length}. Stage-1 reports: ${stage1.length}. Live laws: ${LAW_COUNT}. Disagreements: ${rows.length}.\n\n`;
md += '| Kind | Count |\n|---|---:|\n' + kinds.map((k) => `| ${k} | ${rows.filter((r) => r.kind === k).length} |`).join('\n') + '\n\n';
md += '| Kind | Law | a3 claim | Manifest | Source |\n|---|---|---|---|---|\n';
md += rows.map((r) => `| ${r.kind} | ${r.law} | ${r.claim} | ${r.manifest} | ${r.source} |`).join('\n') + '\n';

if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== md) { console.error(`${OUT} is stale; run node scripts/a3-reconciliation.mjs`); process.exit(1); }
  console.log(`a3 reconciliation up to date (${rows.length} disagreements).`);
} else {
  writeFileSync(OUT, md);
  console.log(`wrote ${OUT}: ${rows.length} disagreements`);
}
